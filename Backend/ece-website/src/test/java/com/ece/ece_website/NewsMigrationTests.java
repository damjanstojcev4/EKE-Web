package com.ece.ece_website;

import com.ece.ece_website.entity.News;
import org.hibernate.boot.MetadataSources;
import org.hibernate.boot.model.naming.CamelCaseToUnderscoresNamingStrategy;
import org.hibernate.boot.registry.StandardServiceRegistryBuilder;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.FileSystemResource;
import org.springframework.jdbc.datasource.init.ScriptUtils;

import java.nio.file.Path;
import java.sql.DriverManager;
import java.time.Instant;
import java.time.LocalDateTime;

import static org.assertj.core.api.Assertions.assertThat;

class NewsMigrationTests {

    @Test
    void migrationPreservesLegacyDataAndPassesHibernateSchemaValidation() throws Exception {
        String url = "jdbc:h2:mem:news_migration";
        try (var connection = DriverManager.getConnection(url, "sa", "");
             var statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE news (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        short_description VARCHAR(1200) NOT NULL,
                        instagram_url VARCHAR(2000) NOT NULL,
                        image_file_path VARCHAR(255),
                        created_at TIMESTAMP(6)
                    )
                    """);
            statement.execute("""
                    INSERT INTO news (short_description, instagram_url, image_file_path, created_at)
                    VALUES ('Legacy summary', 'https://example.org', 'legacy.png', TIMESTAMP '2025-01-01 09:00:00')
                    """);
            var migration = new FileSystemResource(Path.of("..", "..", "deploy", "staging", "migrations",
                    "001-news-publication.sql"));
            ScriptUtils.executeSqlScript(connection, migration);
            ScriptUtils.executeSqlScript(connection, migration);

            var details = new FileSystemResource(Path.of("..", "..", "deploy", "staging", "migrations", "002-news-details.sql"));
            ScriptUtils.executeSqlScript(connection, details);
            ScriptUtils.executeSqlScript(connection, details);
            var registry = new StandardServiceRegistryBuilder()
                    .applySetting("jakarta.persistence.jdbc.url", url)
                    .applySetting("jakarta.persistence.jdbc.user", "sa")
                    .applySetting("hibernate.hbm2ddl.auto", "validate")
                    .build();
            try (var factory = new MetadataSources(registry).addAnnotatedClass(News.class).getMetadataBuilder()
                    .applyPhysicalNamingStrategy(new CamelCaseToUnderscoresNamingStrategy())
                    .build().buildSessionFactory()) {
                factory.inTransaction(session -> {
                    News legacy = session.find(News.class, 1L);
                    assertThat(legacy.getShortDescription()).isEqualTo("Legacy summary");
                    assertThat(legacy.getInstagramUrl()).isEqualTo("https://example.org");
                    assertThat(legacy.getImageFilePath()).isEqualTo("legacy.png");
                    assertThat(legacy.getCreatedAt()).isEqualTo(LocalDateTime.of(2025, 1, 1, 9, 0));
                    assertThat(legacy.getTitle()).isNull();
                    assertThat(legacy.getPublished()).isNull();

                    legacy.setTitle("Editor-supplied title");
                    legacy.setCategory(News.Category.LATEST_NEWS);
                    legacy.setImageAlt("Editor-supplied image description");
                    legacy.setPublishedAt(Instant.parse("2025-01-02T09:00:00Z"));
                    legacy.setPublished(true);
                });
                factory.inSession(session -> {
                    News published = session.find(News.class, 1L);
                    assertThat(published.getTitle()).isEqualTo("Editor-supplied title");
                    assertThat(published.getCategory()).isEqualTo(News.Category.LATEST_NEWS);
                    assertThat(published.getPublishedAt()).isEqualTo(Instant.parse("2025-01-02T09:00:00Z"));
                    assertThat(published.getPublished()).isTrue();
                });
            } finally {
                StandardServiceRegistryBuilder.destroy(registry);
            }
        }
    }
}
