-- New content tables, no seeding and no changes to existing publication state.
CREATE TABLE IF NOT EXISTS opportunities (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slug VARCHAR(160) NOT NULL,
 title VARCHAR(255),
 description VARCHAR(10000),
 category VARCHAR(255),
 location VARCHAR(255),
 start_date DATE,
 end_date DATE,
 opens_at TIMESTAMP(6) WITH TIME ZONE,
 application_deadline TIMESTAMP(6) WITH TIME ZONE,
 application_url VARCHAR(2000),
 published BOOLEAN NOT NULL,
 availability VARCHAR(255),
 country VARCHAR(255),
 minimum_age INTEGER,
 maximum_age INTEGER,
 related_project_uuid UUID,
 created_at TIMESTAMP(6) WITH TIME ZONE,
 updated_at TIMESTAMP(6) WITH TIME ZONE
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_opportunities_slug ON opportunities(slug);
CREATE INDEX IF NOT EXISTS ix_opportunities_public ON opportunities(published,application_deadline);
CREATE TABLE IF NOT EXISTS training_sessions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slug VARCHAR(160) NOT NULL,
 title VARCHAR(255),
 description VARCHAR(10000),
 category VARCHAR(255),
 location VARCHAR(255),
 start_date DATE,
 end_date DATE,
 opens_at TIMESTAMP(6) WITH TIME ZONE,
 registration_deadline TIMESTAMP(6) WITH TIME ZONE,
 registration_url VARCHAR(2000),
 published BOOLEAN NOT NULL,
 availability VARCHAR(255),
 audience VARCHAR(255),
 format VARCHAR(255),
 language VARCHAR(255),
 cost VARCHAR(255),
 learning_objectives VARCHAR(10000),
 training_methods VARCHAR(10000),
 created_at TIMESTAMP(6) WITH TIME ZONE,
 updated_at TIMESTAMP(6) WITH TIME ZONE
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_training_sessions_slug ON training_sessions(slug);
CREATE INDEX IF NOT EXISTS ix_training_sessions_public ON training_sessions(published,registration_deadline);
ALTER TABLE opportunities ADD CONSTRAINT IF NOT EXISTS fk_opportunity_project FOREIGN KEY (related_project_uuid) REFERENCES projects(uuid);
